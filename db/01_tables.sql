-- 01_tables.sql
-- The 42 relations of Section 4.2 of the mid-semester report, one table each.
--
-- Conventions
--   * Names are the report's relation names in snake_case (PlayerGameStats -> player_game_stats).
--   * Columns, primary keys, foreign keys and UNIQUE constraints are copied exactly from Section 4.2.
--   * The structural CHECKs listed in Section 4.2 ("Other keys and checks") are here too.
--     Domain, date and range checks are in 02_checks.sql.
--   * A foreign key the report marks (optional) is nullable; every other foreign key is NOT NULL.
--   * No foreign key cascades deletes: results, stints and identities are history.
--   * Tables are created in dependency order, so every foreign key points at a table that exists.

------------------------------------------------------------------------------
-- Teams and people (part 1: needed by almost everything else)
------------------------------------------------------------------------------

CREATE TABLE region (
    region_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_name   text NOT NULL UNIQUE,
    abbreviation  text NOT NULL UNIQUE
);

CREATE TABLE organization (
    org_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_name  text NOT NULL,
    org_type  text NOT NULL,
    country   text,
    website   text
);

-- Person generalizes Player, Coach and Official (overlapping, partial).
-- full_name [first_name, last_name] is flattened; age() is the view v_person_age;
-- the multivalued {phone_number} is the relation person_phone.
CREATE TABLE person (
    person_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     text NOT NULL,
    last_name      text NOT NULL,
    gamertag       text,                 -- can be empty for officials
    date_of_birth  date,
    nationality    text,
    email          text UNIQUE          -- optional, so a unique identifier, not a candidate key
);

CREATE TABLE person_phone (
    person_id     integer NOT NULL REFERENCES person,
    phone_number  text NOT NULL,
    PRIMARY KEY (person_id, phone_number)
);

CREATE TABLE player (
    person_id      integer PRIMARY KEY REFERENCES person,
    activision_id  text NOT NULL UNIQUE,   -- every player has one: a candidate key
    faceit_id      text UNIQUE,            -- Challengers only: optional
    primary_role   text NOT NULL,
    region_id      integer REFERENCES region   -- player_region, partial
);

-- Coach holds no attributes of its own: it records who is a coach (rule 15 checks against it).
-- coaching_since() is the view v_coaching_since.
CREATE TABLE coach (
    person_id  integer PRIMARY KEY REFERENCES person
);

CREATE TABLE official (
    person_id      integer PRIMARY KEY REFERENCES person,
    official_type  text NOT NULL,
    certified_on   date
);

-- current_name() is the view v_team_current_name.
CREATE TABLE team (
    team_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    founded_date  date,
    status        text NOT NULL DEFAULT 'active'
);

-- Weak entity set owned by Team (team_identity); discriminator valid_from.
-- valid_to is exclusive: the next identity starts on the day this one ends.
-- An empty valid_to marks the current branding.
CREATE TABLE team_identity (
    team_id       integer NOT NULL REFERENCES team,
    valid_from    date NOT NULL,
    team_name     text NOT NULL,
    abbreviation  text,
    home_city     text,
    valid_to      date,
    org_id        integer REFERENCES organization,   -- identity_owner, partial (independent teams)
    PRIMARY KEY (team_id, valid_from),
    CONSTRAINT team_identity_valid_to_check CHECK (valid_to >= valid_from)
);

-- Weak entity set with two owners, Person and Team; discriminator start_date.
-- end_date is exclusive, like valid_to. is_current() is the view v_roster_current.
CREATE TABLE roster (
    person_id     integer NOT NULL REFERENCES person,
    team_id       integer NOT NULL REFERENCES team,
    start_date    date NOT NULL,
    end_date      date,
    roster_role   text NOT NULL,
    join_type     text NOT NULL,
    transfer_fee  numeric(12, 2),
    end_reason    text,
    PRIMARY KEY (person_id, team_id, start_date),
    CONSTRAINT roster_end_date_check CHECK (end_date >= start_date)
);

------------------------------------------------------------------------------
-- Events and structure
------------------------------------------------------------------------------

-- Event generalizes League and Tournament (disjoint, total).
CREATE TABLE event (
    event_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name  text NOT NULL,
    tier        text,
    website     text
);

CREATE TABLE hosted_by (
    event_id   integer NOT NULL REFERENCES event,
    org_id     integer NOT NULL REFERENCES organization,
    host_role  text NOT NULL,
    PRIMARY KEY (event_id, org_id)
);

CREATE TABLE league (
    event_id           integer PRIMARY KEY REFERENCES event,
    abbreviation       text NOT NULL UNIQUE,
    competition_level  text NOT NULL,
    founded_year       smallint,
    min_age            smallint,
    points_awarded_to  text NOT NULL
);

-- Weak entity set owned by League; discriminator season_year.
-- The owner key is renamed by role: league_id (report Section 4.1).
CREATE TABLE season (
    league_id    integer NOT NULL REFERENCES league (event_id),
    season_year  smallint NOT NULL,
    game_title   text NOT NULL,
    start_date   date,
    end_date     date,
    PRIMARY KEY (league_id, season_year)
);

-- Weak entity set owned by Season; discriminator stage_number.
CREATE TABLE stage (
    league_id     integer NOT NULL,
    season_year   smallint NOT NULL,
    stage_number  smallint NOT NULL,
    stage_name    text NOT NULL,
    start_date    date,
    end_date      date,
    PRIMARY KEY (league_id, season_year, stage_number),
    FOREIGN KEY (league_id, season_year) REFERENCES season
);

CREATE TABLE registered_in (
    team_id            integer NOT NULL REFERENCES team,
    league_id          integer NOT NULL,
    season_year        smallint NOT NULL,
    registration_date  date,
    PRIMARY KEY (team_id, league_id, season_year),
    FOREIGN KEY (league_id, season_year) REFERENCES season
);

-- address [street, city, country] is flattened.
CREATE TABLE venue (
    venue_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_name  text NOT NULL,
    street      text,
    city        text,
    country     text,
    capacity    integer
);

CREATE TABLE format (
    format_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    format_name  text NOT NULL UNIQUE,
    description  text
);

------------------------------------------------------------------------------
-- Competitive settings
------------------------------------------------------------------------------

CREATE TABLE map (
    map_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_name    text NOT NULL,
    game_title  text NOT NULL,
    UNIQUE (map_name, game_title)
);

CREATE TABLE game_mode (
    mode_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode_name      text NOT NULL UNIQUE,
    abbreviation   text NOT NULL UNIQUE,
    objective      text,
    win_condition  text
);

CREATE TABLE map_pool (
    pool_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_name    text NOT NULL,
    description  text
);

-- The ternary relationship pool_entry; all-key, in 5NF (report Section 4.3.4).
CREATE TABLE pool_entry (
    pool_id  integer NOT NULL REFERENCES map_pool,
    map_id   integer NOT NULL REFERENCES map,
    mode_id  integer NOT NULL REFERENCES game_mode,
    PRIMARY KEY (pool_id, map_id, mode_id)
);

CREATE TABLE series_layout (
    layout_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layout_name  text NOT NULL
);

-- Weak entity set owned by SeriesLayout; discriminator (best_of, game_number).
CREATE TABLE series_slot (
    layout_id    integer NOT NULL REFERENCES series_layout,
    best_of      smallint NOT NULL,
    game_number  smallint NOT NULL,
    mode_id      integer NOT NULL REFERENCES game_mode,   -- slot_mode, total
    PRIMARY KEY (layout_id, best_of, game_number),
    CONSTRAINT series_slot_game_number_check CHECK (game_number BETWEEN 1 AND best_of)
);

------------------------------------------------------------------------------
-- Events and structure (continued): tournaments and their parts
------------------------------------------------------------------------------

-- prize_pool() is the view v_tournament_prize_pool.
CREATE TABLE tournament (
    event_id         integer PRIMARY KEY REFERENCES event,
    tournament_type  text NOT NULL,
    start_date       date,
    end_date         date,
    max_teams        smallint,
    team_size        smallint NOT NULL,
    league_id        integer,       -- the three stage columns: stage_tournament, partial
    season_year      smallint,
    stage_number     smallint,
    venue_id         integer REFERENCES venue,    -- held_at, partial (online tournaments)
    region_id        integer REFERENCES region,   -- tournament_region, partial
    FOREIGN KEY (league_id, season_year, stage_number) REFERENCES stage,
    CONSTRAINT tournament_stage_all_or_none CHECK (
        (league_id IS NULL) = (season_year IS NULL)
        AND (season_year IS NULL) = (stage_number IS NULL)),
    CONSTRAINT tournament_team_size_check CHECK (team_size > 0)
);

-- Weak entity set owned by Tournament; discriminator phase_number.
-- The owner key is renamed by role: tournament_id.
CREATE TABLE phase (
    tournament_id    integer NOT NULL REFERENCES tournament (event_id),
    phase_number     smallint NOT NULL,
    phase_name       text NOT NULL,
    default_best_of  smallint NOT NULL,
    points_per_win   smallint NOT NULL DEFAULT 0,
    start_date       date,
    end_date         date,
    format_id        integer NOT NULL REFERENCES format,          -- uses_format, total
    pool_id          integer NOT NULL REFERENCES map_pool,        -- uses_pool, total
    layout_id        integer NOT NULL REFERENCES series_layout,   -- uses_layout, total
    PRIMARY KEY (tournament_id, phase_number),
    CONSTRAINT phase_default_best_of_odd CHECK (default_best_of % 2 = 1)
);

-- Weak entity set owned by Tournament; discriminator placement_from.
-- prize_amount is the prize for each team in the band, in USD.
CREATE TABLE placement_reward (
    tournament_id   integer NOT NULL REFERENCES tournament (event_id),
    placement_from  smallint NOT NULL,
    placement_to    smallint NOT NULL,
    points          integer NOT NULL DEFAULT 0,
    prize_amount    numeric(12, 2) NOT NULL DEFAULT 0,
    PRIMARY KEY (tournament_id, placement_from),
    CONSTRAINT placement_reward_band_check CHECK (placement_to >= placement_from)
);

CREATE TABLE participates_in (
    team_id          integer NOT NULL REFERENCES team,
    tournament_id    integer NOT NULL REFERENCES tournament (event_id),
    seed             smallint,
    final_placement  smallint,
    PRIMARY KEY (team_id, tournament_id)
);

------------------------------------------------------------------------------
-- Matches and games
------------------------------------------------------------------------------

-- winner() is the view v_match_winner. winner_to and loser_to are the recursive
-- relationships: each points at the next match and the slot (1 or 2) it feeds.
CREATE TABLE match (
    match_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id       integer NOT NULL,
    phase_number        smallint NOT NULL,
    match_number        smallint NOT NULL,
    round_name          text,
    bracket_side        text,
    best_of             smallint NOT NULL,
    scheduled_at        timestamptz,
    status              text NOT NULL DEFAULT 'scheduled',
    result_type         text,              -- NULL until the match ends
    awarded_team_id     integer,           -- forfeits only; foreign key added after competes_in
    winner_to_match_id  integer REFERENCES match,
    winner_to_slot      smallint,
    loser_to_match_id   integer REFERENCES match,
    loser_to_slot       smallint,
    FOREIGN KEY (tournament_id, phase_number) REFERENCES phase,   -- phase_match, total
    UNIQUE (tournament_id, phase_number, match_number),
    UNIQUE (winner_to_match_id, winner_to_slot),
    UNIQUE (loser_to_match_id, loser_to_slot),
    CONSTRAINT match_winner_to_slot_check CHECK (
        (winner_to_match_id IS NULL) = (winner_to_slot IS NULL)
        AND (winner_to_slot IS NULL OR winner_to_slot IN (1, 2))),
    CONSTRAINT match_loser_to_slot_check CHECK (
        (loser_to_match_id IS NULL) = (loser_to_slot IS NULL)
        AND (loser_to_slot IS NULL OR loser_to_slot IN (1, 2))),
    -- NULL-safe: a NULL result_type cannot slip past this check.
    CONSTRAINT match_awarded_only_on_forfeit CHECK (
        (awarded_team_id IS NOT NULL) = (COALESCE(result_type, '') = 'forfeit')),
    CONSTRAINT match_best_of_odd CHECK (best_of % 2 = 1)
);

-- competes_in: 0..2 teams per match, each in slot 1 or 2.
-- Its key (match_id, team_id) is the target of every "one of the match's teams" foreign key.
CREATE TABLE competes_in (
    match_id  integer NOT NULL REFERENCES match,
    team_id   integer NOT NULL REFERENCES team,
    slot      smallint NOT NULL,
    PRIMARY KEY (match_id, team_id),
    UNIQUE (match_id, slot),
    CONSTRAINT competes_in_slot_check CHECK (slot IN (1, 2))
);

-- match_awarded_to: the awarded team must be one of the match's teams (part of rule 5).
-- Added here because match and competes_in reference each other.
ALTER TABLE match
    ADD CONSTRAINT match_awarded_team_fk
    FOREIGN KEY (match_id, awarded_team_id) REFERENCES competes_in (match_id, team_id);

CREATE TABLE officiates (
    person_id  integer NOT NULL REFERENCES official,
    match_id   integer NOT NULL REFERENCES match,
    duty       text NOT NULL,
    PRIMARY KEY (person_id, match_id)
);

-- Weak entity set owned by Match; discriminator game_number.
-- Stores map_id and mode_id; the pool is the one the match's phase uses, so pool_id
-- is not stored again (report Section 4.3.2, violation 2). winner() is v_game_winner.
CREATE TABLE game (
    match_id          integer NOT NULL REFERENCES match,
    game_number       smallint NOT NULL,
    started_at        timestamptz,
    duration_seconds  integer,
    status            text NOT NULL DEFAULT 'scheduled',
    result_type       text,                -- NULL until the game ends
    map_id            integer NOT NULL REFERENCES map,
    mode_id           integer NOT NULL REFERENCES game_mode,
    awarded_team_id   integer,             -- forfeits only
    PRIMARY KEY (match_id, game_number),
    FOREIGN KEY (match_id, awarded_team_id) REFERENCES competes_in (match_id, team_id),
    CONSTRAINT game_number_check CHECK (game_number >= 1),
    CONSTRAINT game_awarded_only_on_forfeit CHECK (
        (awarded_team_id IS NOT NULL) = (COALESCE(result_type, '') = 'forfeit'))
);

-- team_result: 0..2 teams per game, each with its score.
CREATE TABLE team_result (
    match_id     integer NOT NULL,
    game_number  smallint NOT NULL,
    team_id      integer NOT NULL,
    score        integer NOT NULL,
    PRIMARY KEY (match_id, game_number, team_id),
    FOREIGN KEY (match_id, game_number) REFERENCES game,
    FOREIGN KEY (match_id, team_id) REFERENCES competes_in (match_id, team_id)
);

-- Weak entity set owned by Match; discriminator veto_order.
-- Like game, it stores map_id and mode_id but not pool_id.
CREATE TABLE map_veto (
    match_id    integer NOT NULL REFERENCES match,
    veto_order  smallint NOT NULL,
    action      text NOT NULL,
    vetoed_at   timestamptz,
    team_id     integer NOT NULL,        -- vetoed_by, total
    map_id      integer NOT NULL REFERENCES map,
    mode_id     integer NOT NULL REFERENCES game_mode,
    PRIMARY KEY (match_id, veto_order),
    FOREIGN KEY (match_id, team_id) REFERENCES competes_in (match_id, team_id),
    UNIQUE (match_id, map_id, mode_id)
);

------------------------------------------------------------------------------
-- Player stats
------------------------------------------------------------------------------

-- The ternary relationship played_for (Player, Match -> Team).
-- The arrow on Team makes (person_id, match_id) the key.
CREATE TABLE match_player (
    person_id  integer NOT NULL REFERENCES player,
    match_id   integer NOT NULL,
    team_id    integer NOT NULL,
    PRIMARY KEY (person_id, match_id),
    FOREIGN KEY (match_id, team_id) REFERENCES competes_in (match_id, team_id)
);

-- Weak entity set with two owners, Player and Game; no discriminator.
-- Its Player key is referenced through match_player, so stats exist only for listed players.
-- kd_ratio() is the view v_player_kd.
CREATE TABLE player_game_stats (
    person_id    integer NOT NULL,
    match_id     integer NOT NULL,
    game_number  smallint NOT NULL,
    kills        integer NOT NULL DEFAULT 0,
    deaths       integer NOT NULL DEFAULT 0,
    assists      integer NOT NULL DEFAULT 0,
    damage       integer NOT NULL DEFAULT 0,
    PRIMARY KEY (person_id, match_id, game_number),
    FOREIGN KEY (person_id, match_id) REFERENCES match_player,
    FOREIGN KEY (match_id, game_number) REFERENCES game,
    CONSTRAINT player_game_stats_counts_check CHECK (
        kills >= 0 AND deaths >= 0 AND assists >= 0 AND damage >= 0)
);

-- The four disjoint, total specializations of PlayerGameStats, one per mode.
CREATE TABLE hardpoint_stats (
    person_id               integer NOT NULL,
    match_id                integer NOT NULL,
    game_number             smallint NOT NULL,
    hill_time_seconds       integer NOT NULL DEFAULT 0,
    contested_time_seconds  integer NOT NULL DEFAULT 0,
    captures                integer NOT NULL DEFAULT 0,
    PRIMARY KEY (person_id, match_id, game_number),
    FOREIGN KEY (person_id, match_id, game_number) REFERENCES player_game_stats
);

CREATE TABLE snd_stats (
    person_id     integer NOT NULL,
    match_id      integer NOT NULL,
    game_number   smallint NOT NULL,
    first_bloods  integer NOT NULL DEFAULT 0,
    plants        integer NOT NULL DEFAULT 0,
    defuses       integer NOT NULL DEFAULT 0,
    PRIMARY KEY (person_id, match_id, game_number),
    FOREIGN KEY (person_id, match_id, game_number) REFERENCES player_game_stats
);

CREATE TABLE control_stats (
    person_id       integer NOT NULL,
    match_id        integer NOT NULL,
    game_number     smallint NOT NULL,
    tiers_captured  integer NOT NULL DEFAULT 0,
    ticks           integer NOT NULL DEFAULT 0,
    PRIMARY KEY (person_id, match_id, game_number),
    FOREIGN KEY (person_id, match_id, game_number) REFERENCES player_game_stats
);

CREATE TABLE overload_stats (
    person_id           integer NOT NULL,
    match_id            integer NOT NULL,
    game_number         smallint NOT NULL,
    overloads_scored    integer NOT NULL DEFAULT 0,
    device_pickups      integer NOT NULL DEFAULT 0,
    carry_time_seconds  integer NOT NULL DEFAULT 0,
    PRIMARY KEY (person_id, match_id, game_number),
    FOREIGN KEY (person_id, match_id, game_number) REFERENCES player_game_stats
);

------------------------------------------------------------------------------
-- Operations
------------------------------------------------------------------------------

-- Weak entity set owned by Match; discriminator dispute_number.
CREATE TABLE dispute (
    match_id           integer NOT NULL REFERENCES match,
    dispute_number     smallint NOT NULL,
    reason             text NOT NULL,
    raised_at          timestamptz NOT NULL DEFAULT now(),
    status             text NOT NULL DEFAULT 'open',
    resolution         text,
    resolved_at        timestamptz,
    raised_by_team_id  integer NOT NULL,                     -- raised_by, total
    resolved_by        integer REFERENCES official,          -- resolved_by, partial
    PRIMARY KEY (match_id, dispute_number),
    FOREIGN KEY (match_id, raised_by_team_id) REFERENCES competes_in (match_id, team_id),
    CONSTRAINT dispute_resolved_is_complete CHECK (
        status <> 'resolved' OR (resolved_by IS NOT NULL AND resolved_at IS NOT NULL))
);

-- penalty_match, penalty_game and resulted_from share one match_id column, so a
-- penalty can never point at two different matches (rules 19 and 22).
CREATE TABLE penalty (
    penalty_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    penalty_type    text NOT NULL,
    reason          text NOT NULL,
    issued_at       timestamptz NOT NULL DEFAULT now(),
    start_date      date,
    end_date        date,
    fine_amount     numeric(12, 2),
    issued_by       integer NOT NULL REFERENCES official,   -- issued_by, total
    team_id         integer REFERENCES team,                -- penalized_team, partial
    person_id       integer REFERENCES person,              -- penalized_person, partial
    match_id        integer REFERENCES match,               -- penalty_match, partial
    game_number     smallint,
    dispute_number  smallint,
    FOREIGN KEY (match_id, game_number) REFERENCES game,              -- penalty_game
    FOREIGN KEY (match_id, dispute_number) REFERENCES dispute,        -- resulted_from
    -- Checked only when both are set (MATCH SIMPLE): a named team must be in the match.
    FOREIGN KEY (match_id, team_id) REFERENCES competes_in (match_id, team_id),
    CONSTRAINT penalty_parts_need_match CHECK (
        match_id IS NOT NULL OR (game_number IS NULL AND dispute_number IS NULL)),
    CONSTRAINT penalty_names_someone CHECK (team_id IS NOT NULL OR person_id IS NOT NULL),
    CONSTRAINT penalty_suspension_has_start CHECK (
        penalty_type NOT IN ('suspension', 'ban') OR start_date IS NOT NULL),
    CONSTRAINT penalty_end_date_check CHECK (end_date >= start_date)
);

------------------------------------------------------------------------------
-- Indexes on foreign key columns used for lookups
-- (primary keys and UNIQUE columns are indexed automatically)
------------------------------------------------------------------------------

CREATE INDEX competes_in_team_idx       ON competes_in (team_id);
CREATE INDEX roster_team_idx            ON roster (team_id);
CREATE INDEX participates_in_tourn_idx  ON participates_in (tournament_id);
CREATE INDEX registered_in_season_idx   ON registered_in (league_id, season_year);
CREATE INDEX match_player_match_idx     ON match_player (match_id, team_id);
CREATE INDEX player_game_stats_game_idx ON player_game_stats (match_id, game_number);
CREATE INDEX tournament_stage_idx       ON tournament (league_id, season_year, stage_number);
CREATE INDEX penalty_match_idx          ON penalty (match_id);
